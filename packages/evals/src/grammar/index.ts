/**
 * The source of src/understanding/generated.ts: static imports of the generated files, so they
 * bundle like the hand-written ones. Formatted the way Biome formats it, so `biome check` leaves
 * it alone and the generator's test can compare bytes.
 */
export function generatedIndexSource(ids: readonly string[]): string {
  const lines = [
    "// Generated by scripts/gen-debriefs.ts (`pnpm --filter @earshot/evals debriefs:gen`): the static",
    "// imports of debriefs/generated/d031–d200.json. Don't edit it by hand; a test regenerates it.",
    ...ids.map(
      (id) => `import ${id} from "../../debriefs/generated/${id}.json" with { type: "json" };`,
    ),
    "",
    "/** The generated scripts as their files hold them, by id, before parsing. */",
    "export const GENERATED_RAW: Readonly<Record<string, unknown>> = {",
    ...ids.map((id) => `  ${id},`),
    "};",
    "",
  ];
  return lines.join("\n");
}
